import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { parseModelZip } from '../src/import/parse.ts';
import { buildQuantityRows, quantityCsv, summarizeQuantities } from '../src/quantities.ts';

const fixturePath = path.resolve(process.argv[2] ?? '../bright-revit-exporter/artifacts/BV-1.4.0-final/export-fixture.zip');
const model = await parseModelZip(await readFile(fixturePath), path.basename(fixturePath));
assert.equal(model.components.length, 2);
const byId = new Map(model.components.map(component => [component.id, component]));
const first = byId.get('fixture-1')?.quantitySnapshot;
const second = byId.get('fixture-2')?.quantitySnapshot;
assert.ok(first); assert.ok(second);
assert.equal(model.components.some(component => component.quantityIssue !== undefined), false);
const near = (actual, expected) => assert.ok(Math.abs(actual - expected) < 1e-12, `${actual} != ${expected}`);
near(first.metrics.length.value, 3.048);
near(first.metrics.area.value, 9.290304);
assert.equal(first.metrics.volume.value, 0);
assert.equal(second.metrics.length.status, 'missing');
assert.equal(second.metrics.length.value, null);
near(second.metrics.area.value, 2.322576);
near(second.metrics.volume.value, 0.226534772736);
assert.equal(first.sourceElement.documentScope, 'fixture-project');
assert.equal(first.sourceElement.linkInstanceScope, 'root');
const total = summarizeQuantities(model.components);
assert.equal(total.count, 2); assert.equal(total.recordCount, 2);
near(total.metrics.length.value, 3.048); assert.equal(total.metrics.length.missing, 1);
near(total.metrics.area.value, 11.61288); near(total.metrics.volume.value, 0.226534772736);
assert.ok(quantityCsv(buildQuantityRows(model.components, 'component'), { language: 'en', modelName: model.name, scope: 'C# contract fixture' }).startsWith('\ufeff'));
console.log(JSON.stringify({ result: 'PASS', fixture: fixturePath, quantityObjects: total.count, metrics: total.metrics, hostExportVerified: false }));
